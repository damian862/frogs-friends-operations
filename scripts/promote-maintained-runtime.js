const fs=require('fs');
const path=require('path');

const root=path.resolve(__dirname,'..');
const dist=path.join(root,'dist');
const runtime=['core.js','bookings.js','staffing.js','access.js','calendar.js','billing.js','viewer-access.js'];

if(process.env.GITHUB_HEAD_REF!=='refactor/consolidate-app-modules'){
  console.log('Promotion skipped outside the dedicated refactor PR.');
  process.exit(0);
}
for(const file of [...runtime,'index.html']){
  const source=path.join(dist,file);
  if(!fs.existsSync(source))throw new Error(`Verified build output missing: ${file}`);
  let content=fs.readFileSync(source,'utf8');
  if(file.endsWith('.js'))content=content.replace('/* Generated by scripts/build-bundles.js. Do not edit dist directly. */','/* Maintained consolidated runtime module. */');
  fs.writeFileSync(path.join(root,file),content);
}

for(const file of fs.readdirSync(root)){
  if(/^app-\d+\.js$/.test(file))fs.rmSync(path.join(root,file));
}

const build=`const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const dist=path.join(root,'dist');
const runtime=['core.js','bookings.js','staffing.js','access.js','calendar.js','billing.js','viewer-access.js'];
fs.rmSync(dist,{recursive:true,force:true});
fs.mkdirSync(dist,{recursive:true});
for(const file of [...runtime,'index.html'])fs.copyFileSync(path.join(root,file),path.join(dist,file));
for(const entry of fs.readdirSync(root,{withFileTypes:true}))if(entry.isFile()&&/\.(css|png|jpe?g|svg|ico|webp|woff2?)$/i.test(entry.name))fs.copyFileSync(path.join(root,entry.name),path.join(dist,entry.name));
const manifest={bundleCount:runtime.length,sourceCount:runtime.length,bundles:runtime};
fs.writeFileSync(path.join(dist,'runtime-manifest.json'),JSON.stringify(manifest,null,2)+'\\n');
console.log('Built 7 maintained runtime modules.');
`;
fs.writeFileSync(path.join(root,'scripts/build-bundles.js'),build);

const sharedTest=`global.window=global;
const fs=require('fs');
const path=require('path');
const vm=require('vm');
const assert=require('assert');
const core=fs.readFileSync(path.join(__dirname,'..','core.js'),'utf8');
const marker=core.indexOf('/* source: app-1.js */');
if(marker<0)throw new Error('Unable to isolate shared utilities in core.js');
vm.runInThisContext(core.slice(0,marker),{filename:'core-utils.js'});
assert.strictEqual(OpsUtil.isoDate(new Date(2026,8,7,12)),'2026-09-07');
assert.strictEqual(OpsUtil.parseDate('2026-09-07').getFullYear(),2026);
assert.strictEqual(OpsUtil.hoursBetween('18:00','19:30'),1.5);
assert.strictEqual(OpsUtil.money(4284),'£4,284.00');
assert.deepStrictEqual(OpsUtil.monthBounds('2026-09'),{from:'2026-09-01',to:'2026-09-30',usage_month:'2026-09-01'});
(async()=>{let calls=0;const d=OpsUtil.createBurstDeduper(async key=>{calls++;return key+':'+calls},{windowMs:50,key:key=>key});const [a,b]=await Promise.all([d('x'),d('x')]);assert.strictEqual(a,'x:1');assert.strictEqual(b,'x:1');assert.strictEqual(calls,1);d.invalidate('x');assert.strictEqual(await d('x'),'x:2');console.log('Shared utility smoke tests passed.');})().catch(error=>{console.error(error);process.exitCode=1});
`;
fs.writeFileSync(path.join(root,'tests/shared-utils.test.js'),sharedTest);

const buildTest=`const assert=require('assert');
const fs=require('fs');
const path=require('path');
const {execFileSync}=require('child_process');
const root=path.resolve(__dirname,'..');
const runtime=['core.js','bookings.js','staffing.js','access.js','calendar.js','billing.js','viewer-access.js'];
execFileSync(process.execPath,[path.join(root,'scripts/build-bundles.js')],{cwd:root,stdio:'inherit'});
const manifest=JSON.parse(fs.readFileSync(path.join(root,'dist/runtime-manifest.json'),'utf8'));
assert.strictEqual(manifest.bundleCount,7);assert.strictEqual(manifest.sourceCount,7);assert.deepStrictEqual(manifest.bundles,runtime);
assert.strictEqual(fs.readdirSync(root).filter(f=>/^app-\\d+\\.js$/.test(f)).length,0,'legacy app-N files remain');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
for(const file of runtime){assert(index.includes('<script src="'+file+'"></script>'),'index missing '+file);execFileSync(process.execPath,['--check',path.join(root,file)],{stdio:'pipe'});}
assert(!index.includes('app-15.js'),'legacy entry point remains');
const combined=runtime.map(f=>fs.readFileSync(path.join(root,f),'utf8')).join('\\n');
assert(combined.includes('OpsLifecycle.use('),'flattened lifecycle registry missing');
assert(!combined.includes("const chain=['app-16.js'"),'legacy dynamic loader remains');
console.log('Maintained runtime build tests passed.');
`;
fs.writeFileSync(path.join(root,'tests/build-bundles.test.js'),buildTest);

const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
delete pkg.devDependencies;
pkg.scripts={build:'node scripts/build-bundles.js',test:'node tests/shared-utils.test.js && node tests/build-bundles.test.js'};
pkg.engines={node:'24.x'};
fs.writeFileSync(path.join(root,'package.json'),JSON.stringify(pkg,null,2)+'\n');

